package calculations;

public class calculations {

    public double add(double first, double second) {       // Addition
        return first + second;
    }
    public double subtract(double first, double second) {  // Subtraction
        return first - second;
    }
    public double multiply(double first, double second) {  // Multiplication
        return first * second;
    }
    public double divide(double first, double second) {    // Division
        return first / second;
    }
}